import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const serverRoot=path.resolve(import.meta.dirname,'..');
export function generateInitSql(database='ctump_docugov') {
  if(!/^[A-Za-z0-9_]+$/.test(database))throw new Error('Tên database chỉ được chứa chữ, số và dấu gạch dưới.');
  let schema=fs.readFileSync(path.join(serverRoot,'schema.sql'),'utf8').replaceAll('\r\n','\n');
  const replace=(pattern,value)=>{
    if(!pattern.test(schema))throw new Error('Schema đã thay đổi; cần cập nhật bộ tạo SQL trước khi xuất.');
    schema=schema.replace(pattern,()=>value);
  };
  replace(/^    'COMPLETED'$/m,"    'COMPLETED',\n    'DRAFT',\n    'CANCELLED'");
  replace(/^  `change_summary` TEXT NULL,$/m,'  `change_summary` TEXT NULL,\n  `snapshot` JSON NULL,');
  replace(/^  `step_name` VARCHAR\(100\) NOT NULL,$/m,'  `step_name` VARCHAR(100) NOT NULL,\n  `attachments` JSON NULL,\n  `attempts` INT NOT NULL DEFAULT 0,\n  `last_error` TEXT NULL,\n  `next_attempt_at` TIMESTAMP NULL,');
  replace(/^  `sent_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,$/m,'  `sent_at` TIMESTAMP NULL DEFAULT NULL,');
  // Retain official department choices, without fictional contact/head names.
  const seed=schema.match(/INSERT IGNORE INTO `departments`[\s\S]*?;/)?.[0];
  if(!seed)throw new Error('Không tìm thấy danh mục đơn vị.');
  const departments=[...seed.matchAll(/^\('([^']*)', '([^']*)', '([^']*)', '([^']*)'/gm)];
  if(!departments.length)throw new Error('Không đọc được danh mục đơn vị.');
  schema=schema.replace(seed,()=>"INSERT IGNORE INTO `departments` (`id`,`code`,`name`,`short_name`) VALUES\n"+departments.map(row=>"('"+row.slice(1).join("', '")+"')").join(',\n')+';');
  schema=schema.replace('-- Cấu trúc tham chiếu an toàn. Dùng npm run db:migrate để nâng cấp database hiện có.','-- Chỉ khởi tạo database mới. Database schema cũ cần dùng npm run db:migrate.');
  const extra=[
    'CREATE TABLE IF NOT EXISTS `schema_migrations` (',
    '  `version` VARCHAR(80) NOT NULL,',
    '  `applied_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,',
    '  PRIMARY KEY (`version`)',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;',
    '',
    'CREATE TABLE IF NOT EXISTS `auth_credentials` (',
    '  `user_id` VARCHAR(50) NOT NULL,',
    '  `password_hash` VARCHAR(255) NULL,',
    '  `token_version` INT NOT NULL DEFAULT 0,',
    '  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,',
    '  PRIMARY KEY (`user_id`),',
    '  CONSTRAINT `fk_credential_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;',
    '',
    'CREATE TABLE IF NOT EXISTS `dossier_sequences` (',
    '  `year` INT NOT NULL,',
    '  `last_number` INT NOT NULL,',
    '  PRIMARY KEY (`year`)',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;',
  ].join('\n');
  const body=schema+'\n'+extra+'\n';
  const tables=[...body.matchAll(/CREATE TABLE IF NOT EXISTS `([a-z0-9_]+)`\s*\(([\s\S]*?)\) ENGINE[^;]*;/g)];
  let columnCount=0;
  const columns=tables.map(table=>{
    const names=[...table[2].matchAll(/^\s*`([a-z0-9_]+)`\s+/gm)].map(match=>match[1]);columnCount+=names.length;
    return "    (TABLE_NAME='"+table[1]+"' AND COLUMN_NAME IN ('"+names.join("','")+"'))";
  }).join(' OR\n');
  const migration=fs.readFileSync(path.join(serverRoot,'src/db/migrate.js'),'utf8').match(/export const migrationVersion = '([^']+)'/)?.[1];
  if(!migration)throw new Error('Không đọc được phiên bản migration.');
  return [
    '-- CGCN: standalone MySQL 8+ initialization. Generated by npm run db:sql.',
    '-- Chạy trong mysql: SOURCE C:/duong-dan-project/server/init-production.sql;',
    '-- File không có DROP/TRUNCATE/DELETE và không tạo tài khoản/hồ sơ demo.',
    '-- Đổi tên DB tại hai dòng CREATE DATABASE / USE nếu cần; cập nhật DB_NAME tương ứng.',
    'SET NAMES utf8mb4;',
    "SET time_zone = '+00:00';",
    'CREATE DATABASE IF NOT EXISTS `'+database+'` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;',
    'USE `'+database+'`;',
    '',body,
    '-- Chỉ đánh dấu sẵn sàng khi toàn bộ cột runtime đã tồn tại.',
    'INSERT IGNORE INTO `schema_migrations` (`version`)',
    "SELECT '"+migration+"' WHERE (",
    '  SELECT COUNT(*) FROM information_schema.COLUMNS',
    '  WHERE TABLE_SCHEMA=DATABASE() AND (',columns,
    '  )',
    ') = '+columnCount+';',
    '',
    "SELECT DATABASE() AS database_name, IF(EXISTS(SELECT 1 FROM schema_migrations WHERE version='"+migration+"'), 'READY', 'SCHEMA_INCOMPATIBLE: run npm run db:migrate') AS initialization_status;",
    '',
  ].join('\n');
}

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
  const index=process.argv.indexOf('--database');
  const database=index<0?'ctump_docugov':process.argv[index+1];
  if(!database)throw new Error('Thiếu tên database sau --database.');
  const file=path.join(serverRoot,'init-production.sql');
  fs.writeFileSync(file,generateInitSql(database));
  console.log('Đã tạo '+file+' cho database '+database+'. Không kết nối hoặc thay đổi database hiện tại.');
}
